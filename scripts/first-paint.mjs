import { bundleHarness, electronBinary, ROOT, runElectron } from '../test/parity/harness/bundle.mjs';

export const GATE_MS = 1000;
const APP_DIR = join(ROOT, 'packages/app');
const DEFAULT_DECK = join(ROOT, 'fixtures/perf/out/perf-2mb.html');
const IS_ROOT = process.platform === 'linux' && process.getuid?.() === 0;
/** An isolated world of the deck view for the read-outs (never the page's world). */
const READ_WORLD = 1051;

function usage(msg) {
  if (msg) console.error(`first-paint: ${msg}`);
  console.error('usage: node scripts/first-paint.mjs [--deck f.html] [--runs 5] [--trust trusted|protected|both] [--no-warm] [--no-cold] [--no-profile] [--out f.json] [--work dir]');
  process.exit(2);
}

function parseArgs(argv) {
  const o = { deck: null, runs: 5, trust: ['trusted', 'protected'], warm: true, cold: true, profile: true, out: null, work: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const val = () => argv[++i] ?? usage(`${a} needs a value`);
    if (a === '--deck') o.deck = resolve(val());
    else if (a === '--runs') o.runs = Number(val());
    else if (a === '--trust') {
      const t = val();
      o.trust = t === 'both' ? ['trusted', 'protected'] : t === 'trusted' || t === 'protected' ? [t] : usage(`--trust ${t}`);
    } else if (a === '--no-warm') o.warm = false;
    else if (a === '--no-cold') o.cold = false;
    else if (a === '--no-profile') o.profile = false;
    else if (a === '--out') o.out = resolve(val());
    else if (a === '--work') o.work = resolve(val());
    else usage(`unknown argument ${a}`);
  }
  if (!Number.isInteger(o.runs) || o.runs < 1 || o.runs > 50) usage('--runs takes 1..50');
  return o;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export function median(xs) {
  const s = xs.filter((x) => typeof x === 'number' && Number.isFinite(x)).sort((a, b) => a - b);
  if (!s.length) return null;
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

export function medians(runs) {
  const keys = new Set(runs.flatMap((r) => Object.keys(r)));
  return Object.fromEntries([...keys].filter((k) => runs.some((r) => typeof r[k] === 'number')).map((k) => [k, median(runs.map((r) => r[k]))]));
}

/**
 * The counted runs of one case: how many there were, how many failed (an `error` entry: no paint within the
 * deadline), and the medians of the runs that were measured. A failed run is never dropped silently: the
 * table prints the count and the gate fails on it (caseMeets).
 */
export function summarize(runs) {
  const measured = runs.filter((r) => !r.error);
  return { counted: runs.length, measured: measured.length, failed: runs.length - measured.length, errors: [...new Set(runs.filter((r) => r.error).map((r) => r.error))], median: medians(measured) };
}

/** Whether one case meets the gate: every counted run painted, and the median of `key` is under GATE_MS. */
export function caseMeets(summary, key) {
  return !!summary && summary.counted > 0 && summary.failed === 0 && typeof summary.median[key] === 'number' && summary.median[key] < GATE_MS;
}

/** The table's "Runs" cell: how many runs the row's median uses. */
export function runsLabel(summary) {
  if (!summary) return '';
  return summary.failed ? `${summary.measured} of ${summary.counted} (${summary.failed} failed)` : `${summary.counted} of ${summary.counted}`;
}

/** The URL without its fragment: a deck may write its slide into the hash (#1, #/1) as soon as it loads. */
export function withoutFragment(url) {
  const i = url.indexOf('#');
  return i < 0 ? url : url.slice(0, i);
}

/**
 * Whether `url` is a deck view (or render window) URL of the file `name`: blueline://<docId>/<name>, with any
 * fragment or query ignored. Most of Josh's decks write location.hash on load (10 of 12), so comparing the
 * whole URL never found their page (review finding 36).
 */
export function isDeckUrlFor(url, name) {
  if (typeof url !== 'string' || !url.startsWith('blueline://')) return false;
  let u = withoutFragment(url);
  const q = u.indexOf('?');
  if (q >= 0) u = u.slice(0, q);
  try {
    u = decodeURIComponent(u);
  } catch {
    return false;
  }
  return u.endsWith(`/${name}`);
}

/**
 * When main started the navigation that loaded the painted document of webContents `id`: its last main-frame,
 * cross-document navigation at or before the first contentful paint (`fcp`, epoch ms; null: any). A hash or
 * history.replaceState the deck does on load is a same-document navigation of the same page, often after
 * the paint; counting it made "open → main nav" later than the paint itself (review finding 36).
 */
export function documentNavAt(navs, id, fcp) {
  let at = null;
  for (const n of navs) {
    if (n.id !== id || n.sameDocument || n.mainFrame === false) continue;
    if (fcp !== null && fcp !== undefined && n.at > fcp) continue;
    if (at === null || n.at > at) at = n.at;
  }
  return at;
}

/** Resolves to `p`'s value, or to `fallback` after `ms` (a hung renderer must not stall a run past its deadline). */
function within(p, ms, fallback = null) {
  let timer;
  return Promise.race([Promise.resolve(p).catch(() => fallback), new Promise((r) => (timer = setTimeout(() => r(fallback), ms)))]).finally(() => clearTimeout(timer));
}

/** The environment of every app run: no proxy variables (nothing here goes to the network), a fixed display. */
function appEnv(extra) {
  const env = { ...process.env, ...extra };
  for (const k of Object.keys(env)) if (/^(https?|all|no)_proxy$/i.test(k)) delete env[k];
  delete env.BLUELINE_TEST;
  delete env.ELECTRON_RUN_AS_NODE;
  return env;
}

// ------------------------------------------------------------------------------------------- display

async function freePort() {
  return new Promise((res, rej) => {
    const s = createServer();
    s.listen(0, '127.0.0.1', () => {
      const p = s.address().port;
      s.close(() => res(p));
    });
    s.on('error', rej);
  });
}

/** One Xvfb (3840×2160, PHASE0-FINDINGS F4) for every launch, so no xvfb-run start is counted in a run. */
async function ensureDisplay() {
  if (process.platform !== 'linux' || process.env.DISPLAY) return { display: process.env.DISPLAY ?? null, stop: () => undefined };
  for (let n = 160; n < 220; n++) {
    if (existsSync(`/tmp/.X${n}-lock`) || existsSync(`/tmp/.X11-unix/X${n}`)) continue;
    const child = spawn('Xvfb', [`:${n}`, '-screen', '0', '3840x2160x24', '-nolisten', 'tcp', '-ac'], { stdio: 'ignore' });
    let exited = false;
    child.once('exit', () => (exited = true));
    child.once('error', () => (exited = true));
    for (let t = 0; t < 200 && !exited && !existsSync(`/tmp/.X11-unix/X${n}`); t++) await sleep(50);
    if (exited || !existsSync(`/tmp/.X11-unix/X${n}`)) {
      child.kill('SIGKILL');
      continue;
    }
    process.once('exit', () => child.kill('SIGKILL'));
    return { display: `:${n}`, stop: () => child.kill('SIGTERM') };
  }
  throw new Error('no free X display for Xvfb');
}

// ------------------------------------------------------------------------------------------- page timings

/**
 * What the deck view's page knows about its own load (Navigation and Paint Timing), as an expression.
 * `deckView`: the page has the deck preload's overlay host, which only the visible deck view mounts. The
 * document's background render windows (slide index, thumbnails, started once the deck view has loaded) load
 * the same blueline:// URL in render mode, with no overlay; without this check the cold runs sometimes timed a
 * render window's paint (a target list does not say which view a page belongs to).
 */
const PAGE_TIMINGS = `(function(){var p=performance.getEntriesByType('paint').map(function(e){return {name:e.name,startTime:e.startTime}});
var n=performance.getEntriesByType('navigation')[0];
return {timeOrigin:performance.timeOrigin,url:location.href,deckView:!!document.querySelector('blueline-overlay'),paints:p,nav:n?{requestStart:n.requestStart,responseStart:n.responseStart,responseEnd:n.responseEnd,domInteractive:n.domInteractive,domContentLoadedEventEnd:n.domContentLoadedEventEnd,loadEventEnd:n.loadEventEnd,transferSize:n.transferSize,decodedBodySize:n.decodedBodySize}:null}})()`;

/** Wall-clock (epoch ms) marks of one page load from its timings: navigation start, first byte, … first contentful paint. */
function marks(t) {
  const fcp = t.paints.find((p) => p.name === 'first-contentful-paint');
  const fp = t.paints.find((p) => p.name === 'first-paint');
  const at = (ms) => (typeof ms === 'number' && ms > 0 ? t.timeOrigin + ms : null);
  return {
    navStart: t.timeOrigin,
    requestStart: at(t.nav?.requestStart),
    responseStart: at(t.nav?.responseStart),
    responseEnd: at(t.nav?.responseEnd),
    domInteractive: at(t.nav?.domInteractive),
    firstPaint: fp ? t.timeOrigin + fp.startTime : null,
    fcp: fcp ? t.timeOrigin + fcp.startTime : null,
  };
}

/** The phases of one load, in ms: protocol (request to first byte), body, parse and paint. */
function phases(m) {
  const d = (a, b) => (a !== null && b !== null ? b - a : null);
  return {
    navToRequest: d(m.navStart, m.requestStart),
    protocolFirstByte: d(m.requestStart, m.responseStart),
    protocolBody: d(m.responseStart, m.responseEnd),
    responseEndToFcp: d(m.responseEnd, m.fcp),
    navToFcp: d(m.navStart, m.fcp),
  };
}

// ------------------------------------------------------------------------------------------- bare Electron

async function bareElectron(work, runs, display) {
  const main = join(work, 'bare-main.cjs');
  writeFileSync(main, "const { app } = require('electron');\napp.whenReady().then(() => { process.stdout.write('READY ' + Date.now() + '\\n'); app.exit(0); });\n");
  const out = [];
  for (let i = 0; i < runs + 1; i++) {
    const t0 = Date.now();
    const ready = await new Promise((res) => {
      const args = [...(IS_ROOT ? ['--no-sandbox'] : []), main];
      const c = spawn(electronBinary(), args, { env: appEnv({ DISPLAY: display ?? '' }), stdio: ['ignore', 'pipe', 'ignore'] });
      let at = null;
      c.stdout.on('data', (b) => {
        const m = /READY (\d+)/.exec(b.toString());
        if (m) at = Number(m[1]);
      });
      c.on('exit', () => res(at));
    });
    if (i > 0 && ready) out.push({ toReady: ready - t0 });
  }
  return { runs: out, median: medians(out) };
}

// ------------------------------------------------------------------------------------------- warm

async function warmRuns(o, trust, work, display) {
  const { _electron } = await import('@playwright/test');
  const userData = mkdtempSync(join(work, `ud-warm-${trust}-`));
  const env = appEnv({ BLUELINE_USER_DATA: userData, DISPLAY: display ?? '' });
  const first = join(ROOT, 'fixtures/decks/single.html');
  const app = await _electron.launch({ executablePath: electronBinary(), args: [APP_DIR, first], env, chromiumSandbox: !IS_ROOT, timeout: 60_000 });
  const runs = [];
  const plain = [];
  let warmup = null;
  try {
    // The app is running with a window open, its deck loaded.
    for (let t = 0; t < 300; t++) {
      const ok = await app.evaluate(({ webContents }) => webContents.getAllWebContents().some((w) => w.getURL().startsWith('blueline://') && !w.isLoading()));
      if (ok) break;
      await sleep(100);
    }
    await sleep(1000);
    // Main-side marks: when the open request arrives (before the app's own listener runs), and when main
    // starts each main-frame navigation of a blueline:// page (same-document ones flagged: documentNavAt).
    await app.evaluate(({ app: a }) => {
      const g = globalThis;
      if (g.__blFirstPaint) return;
      g.__blFirstPaint = { opens: [], navs: [] };
      a.prependListener('second-instance', () => g.__blFirstPaint.opens.push(performance.timeOrigin + performance.now()));
      a.on('web-contents-created', (_e, wc) => {
        wc.on('did-start-navigation', (d) => {
          if (d.isMainFrame && typeof d.url === 'string' && d.url.startsWith('blueline://')) {
            g.__blFirstPaint.navs.push({ id: wc.id, url: d.url, at: performance.timeOrigin + performance.now(), sameDocument: d.isSameDocument, mainFrame: true });
          }
        });
      });
    });
    for (let i = 0; i < o.runs + 1; i++) {
      const name = `perf-warm-${trust}-${i}.html`;
      const file = join(work, 'decks', name);
      copyFileSync(o.deck, file);
      const opensBefore = await app.evaluate(() => globalThis.__blFirstPaint.opens.length);
      // Every run starts with the first window only (the windows of earlier runs are closed below).
      const windowsBefore = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().length);
      const spawnAt = Date.now();
      const second = spawn(electronBinary(), [...(IS_ROOT ? ['--no-sandbox'] : []), APP_DIR, ...(trust === 'protected' ? ['--protected'] : []), file], { env, stdio: 'ignore' });
      let timings = null;
      let deckId = null;
      let seenIds = [];
      const deadline = Date.now() + 30_000;
      while (Date.now() < deadline) {
        // The pages of this file (the URL without its fragment), then their timings; only the deck view has
        // the overlay host (PAGE_TIMINGS deckView), never one of the document's render windows on that URL.
        const pages = await app.evaluate(({ webContents }) =>
          webContents
            .getAllWebContents()
            .filter((wc) => !wc.isDestroyed())
            .map((wc) => ({ id: wc.id, url: wc.getURL() })),
        );
        const ids = pages.filter((p) => isDeckUrlFor(p.url, name)).map((p) => p.id);
        if (ids.length) seenIds = ids;
        const r = ids.length
          ? await app.evaluate(
              async ({ webContents }, { ids, world, code, readMs }) => {
                for (const wc of webContents.getAllWebContents()) {
                  if (!ids.includes(wc.id) || wc.isDestroyed()) continue;
                  // A hung renderer must not stall the run past its deadline.
                  const t = await Promise.race([wc.executeJavaScriptInIsolatedWorld(world, [{ code }]).catch(() => null), new Promise((res) => setTimeout(() => res(null), readMs))]);
                  if (t?.deckView) return { id: wc.id, t };
                }
                return null;
              },
              { ids, world: READ_WORLD, code: PAGE_TIMINGS, readMs: 2000 },
            )
          : null;
        if (r?.t?.paints?.some((p) => p.name === 'first-contentful-paint') && r.t.nav?.responseEnd > 0) {
          timings = r.t;
          deckId = r.id;
          break;
        }
        await sleep(30);
      }
      await new Promise((res) => (second.exitCode !== null ? res() : second.once('exit', res)));
      const fp = await app.evaluate(() => globalThis.__blFirstPaint);
      const openAt = fp.opens.length > opensBefore ? fp.opens[fp.opens.length - 1] : null;
      const result = (() => {
        if (!timings) return { error: 'no first contentful paint within 30 s' };
        const m = marks(timings);
        const mainNav = documentNavAt(fp.navs, deckId, m.fcp);
        return {
          fromOpen: openAt !== null ? m.fcp - openAt : null,
          fromSpawn: m.fcp - spawnAt,
          spawnToOpen: openAt !== null ? openAt - spawnAt : null,
          openToMainNav: openAt !== null && mainNav !== null ? mainNav - openAt : null,
          openToNavStart: openAt !== null ? m.navStart - openAt : null,
          ...phases(m),
          transferSize: timings.nav?.decodedBodySize ?? null,
          windowsBefore,
        };
      })();
      // The first open of the session warms code paths; it is not counted (and never enters the runs).
      if (i === 0) warmup = result;
      else runs.push(result);
      // Close that window so every run starts from the same app state (one other window open); after a failed
      // run, the window of any page of that file. The deck view sits in a container view (window.ts slot), so
      // the window's own children are not enough: before, no deck window was ever closed, and each warm run
      // shared the machine with the windows (and render windows) of the runs before it.
      await app.evaluate(({ BrowserWindow }, ids) => {
        const has = (v) => v.webContents && ids.includes(v.webContents.id);
        for (const w of BrowserWindow.getAllWindows()) {
          if (w.contentView.children.some((c) => has(c) || (c.children ?? []).some(has))) w.close();
        }
      }, deckId !== null ? [deckId] : seenIds);
      await sleep(1500);
    }
    // Baseline: the same deck in a plain window of the same app process (file://, no preload, no protocol, a
    // partition of its own), the size of a deck view: what Chromium alone takes from navigation to paint.
    for (let i = 0; i < o.runs + 1; i++) {
      const file = join(work, 'decks', `perf-plain-${trust}-${i}.html`);
      copyFileSync(o.deck, file);
      const t = await app.evaluate(
        async ({ BrowserWindow }, { url, world, code, part }) => {
          const w = new BrowserWindow({ show: true, width: 1600, height: 900, useContentSize: true, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, partition: part } });
          try {
            void w.loadURL(url);
            const end = Date.now() + 30_000;
            while (Date.now() < end) {
              await new Promise((r) => setTimeout(r, 30));
              const r = await Promise.race([w.webContents.executeJavaScriptInIsolatedWorld(world, [{ code }]).catch(() => null), new Promise((res) => setTimeout(() => res(null), 2000))]);
              if (r?.paints?.some((p) => p.name === 'first-contentful-paint') && r.nav?.responseEnd > 0) return r;
            }
            return null;
          } finally {
            w.destroy();
          }
        },
        { url: `file://${file}`, world: READ_WORLD, code: PAGE_TIMINGS, part: `fp-plain-${trust}-${i}` },
      );
      if (i > 0) plain.push(t ? phases(marks(t)) : { error: 'no first contentful paint within 30 s' });
    }
  } finally {
    await app.close().catch(() => undefined);
    rmSync(userData, { recursive: true, force: true });
  }
  return { runs, warmup, ...summarize(runs), plain: { runs: plain, ...summarize(plain) } };
}

// ------------------------------------------------------------------------------------------- cold

async function cdp(wsUrl) {
  const ws = new WebSocket(wsUrl);
  await new Promise((res, rej) => {
    const timer = setTimeout(() => rej(new Error('CDP connection timed out')), 5000);
    ws.onopen = () => {
      clearTimeout(timer);
      res();
    };
    ws.onerror = () => {
      clearTimeout(timer);
      rej(new Error('CDP connection failed'));
    };
  });
  let id = 0;
  const pending = new Map();
  ws.onmessage = (ev) => {
    const msg = JSON.parse(typeof ev.data === 'string' ? ev.data : Buffer.from(ev.data).toString());
    if (msg.id && pending.has(msg.id)) {
      pending.get(msg.id)(msg);
      pending.delete(msg.id);
    }
  };
  const send = (method, params = {}) =>
    new Promise((res, rej) => {
      const n = ++id;
      pending.set(n, (m) => (m.error ? rej(new Error(m.error.message)) : res(m.result)));
      ws.send(JSON.stringify({ id: n, method, params }));
    });
  return { send, close: () => ws.close() };
}

/**
 * Evaluates `expression` in an isolated world of page target `t` (not the page's own world); null after 3 s
 * (a hung renderer must not stall a run past its deadline).
 */
async function evalIsolated(t, expression) {
  let c = null;
  const read = (async () => {
    c = await cdp(t.webSocketDebuggerUrl);
    const w = await c.send('Page.createIsolatedWorld', { frameId: t.id, worldName: 'bl-first-paint' });
    const r = await c.send('Runtime.evaluate', { expression, contextId: w.executionContextId, returnByValue: true });
    return r.result?.value ?? null;
  })();
  try {
    return await within(read, 3000);
  } finally {
    c?.close();
    read.then(() => c?.close(), () => undefined);
  }
}

async function coldRun(o, trust, work, display, userData, i) {
  const name = `perf-cold-${trust}-${i}.html`;
  const file = join(work, 'decks', name);
  copyFileSync(o.deck, file);
  const port = await freePort();
  const env = appEnv({ BLUELINE_USER_DATA: userData, DISPLAY: display ?? '' });
  const t0 = Date.now();
  const child = spawn(electronBinary(), [...(IS_ROOT ? ['--no-sandbox'] : []), `--remote-debugging-port=${port}`, APP_DIR, ...(trust === 'protected' ? ['--protected'] : []), file], { env, stdio: 'ignore' });
  let deck = null;
  let shell = null;
  const deadline = Date.now() + 60_000;
  try {
    while (Date.now() < deadline && !deck) {
      let list = [];
      try {
        list = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
      } catch {
        await sleep(20);
        continue;
      }
      // The deck view (its URL without the fragment), not a render window on the same URL (PAGE_TIMINGS deckView).
      const targets = list.filter((t) => t.type === 'page' && isDeckUrlFor(t.url, name));
      for (const target of targets) {
        const t = await evalIsolated(target, PAGE_TIMINGS).catch(() => null);
        if (t?.deckView && t.paints?.some((p) => p.name === 'first-contentful-paint') && t.nav?.responseEnd > 0) {
          deck = t;
          const sh = list.find((x) => x.type === 'page' && String(x.url).startsWith('app://shell/'));
          if (sh) shell = await evalIsolated(sh, 'performance.timeOrigin').catch(() => null);
          break;
        }
      }
      await sleep(20);
    }
  } finally {
    child.kill('SIGTERM');
    const done = await Promise.race([new Promise((r) => (child.exitCode !== null ? r(true) : child.once('exit', () => r(true)))), sleep(10_000).then(() => false)]);
    if (!done) child.kill('SIGKILL');
  }
  if (!deck) return { error: 'no first contentful paint within 60 s' };
  const m = marks(deck);
  return {
    fromStart: m.fcp - t0,
    startToShellNav: typeof shell === 'number' ? shell - t0 : null,
    shellNavToDeckNav: typeof shell === 'number' ? m.navStart - shell : null,
    startToDeckNav: m.navStart - t0,
    ...phases(m),
  };
}

async function coldRuns(o, trust, work, display) {
  const userData = mkdtempSync(join(work, `ud-cold-${trust}-`));
  const runs = [];
  let warmup = null;
  let profile = null;
  try {
    for (let i = 0; i < o.runs + 1; i++) {
      const r = await coldRun(o, trust, work, display, userData, i);
      // The first start creates the profile and warms the file cache: not counted.
      if (i === 0) warmup = r;
      else runs.push(r);
      await sleep(500);
    }
    if (o.profile) profile = await profileColdStart(o, trust, work, display, userData).catch((e) => ({ error: e.message }));
  } finally {
    rmSync(userData, { recursive: true, force: true });
  }
  return { runs, warmup, ...summarize(runs), profile };
}

// ------------------------------------------------------------------------------------------- profile

/**
 * Where main spends a cold start: one extra start under the Node inspector (--inspect-brk), with the V8 CPU
 * profiler running from the first line of main until the deck view's first contentful paint. The inspector
 * and the sampling slow the start a little, so the run gives shares, not the gate's timing.
 */
async function profileColdStart(o, trust, work, display, userData) {
  const name = `perf-profile-${trust}.html`;
  const file = join(work, 'decks', name);
  copyFileSync(o.deck, file);
  const [rdp, inspect] = [await freePort(), await freePort()];
  const env = appEnv({ BLUELINE_USER_DATA: userData, DISPLAY: display ?? '' });
  const t0 = Date.now();
  const child = spawn(
    electronBinary(),
    [...(IS_ROOT ? ['--no-sandbox'] : []), `--inspect-brk=${inspect}`, `--remote-debugging-port=${rdp}`, APP_DIR, ...(trust === 'protected' ? ['--protected'] : []), file],
    { env, stdio: 'ignore' },
  );
  let node = null;
  try {
    let target = null;
    for (let t = 0; t < 400 && !target; t++) {
      try {
        target = (await (await fetch(`http://127.0.0.1:${inspect}/json/list`)).json())[0] ?? null;
      } catch {
        await sleep(25);
      }
    }
    if (!target) throw new Error('the Node inspector did not answer');
    node = await cdp(target.webSocketDebuggerUrl);
    await node.send('Profiler.enable');
    await node.send('Profiler.setSamplingInterval', { interval: 200 });
    await node.send('Profiler.start');
    const resumedAt = Date.now();
    await node.send('Runtime.runIfWaitingForDebugger');
    let fcpAt = null;
    for (const deadline = Date.now() + 60_000; Date.now() < deadline && fcpAt === null; ) {
      try {
        const list = await (await fetch(`http://127.0.0.1:${rdp}/json/list`)).json();
        // The deck view (its URL without the fragment), not a render window on the same URL (PAGE_TIMINGS deckView).
        for (const t of list.filter((x) => x.type === 'page' && isDeckUrlFor(x.url, name))) {
          const tm = await evalIsolated(t, PAGE_TIMINGS).catch(() => null);
          const m = tm?.deckView ? marks(tm) : null;
          if (m?.fcp) {
            fcpAt = m.fcp;
            break;
          }
        }
      } catch {
        // not up yet
      }
      if (fcpAt === null) await sleep(25);
    }
    const { profile } = await node.send('Profiler.stop');
    return { ...summarizeProfile(profile, resumedAt, fcpAt), spawnToResume: resumedAt - t0, resumeToFcp: fcpAt !== null ? fcpAt - resumedAt : null };
  } finally {
    node?.close();
    child.kill('SIGTERM');
    const done = await Promise.race([new Promise((r) => (child.exitCode !== null ? r(true) : child.once('exit', () => r(true)))), sleep(10_000).then(() => false)]);
    if (!done) child.kill('SIGKILL');
  }
}

/** Self and inclusive time per function of the app's bundles (main.cjs, editor.cjs) and per script, in ms. */
function summarizeProfile(profile, resumedAt, fcpAt) {
  const byId = new Map(profile.nodes.map((n) => [n.id, n]));
  const parent = new Map();
  for (const n of profile.nodes) for (const c of n.children ?? []) parent.set(c, n.id);
  const short = (url) => (url ? url.replace(/^.*\/(dist|node_modules|lib)\//, '$1/').replace(/^file:\/\//, '') : '(native)');
  const label = (cf) => `${cf.functionName || '(anonymous)'} ${short(cf.url)}:${cf.lineNumber + 1}`;
  const self = new Map();
  const incl = new Map();
  const perScript = new Map();
  // Samples are attributed only up to the first contentful paint (profile time is µs since profile start).
  const limitUs = fcpAt !== null ? (fcpAt - resumedAt) * 1000 : Infinity;
  let t = 0;
  let busy = 0;
  for (let i = 0; i < profile.samples.length; i++) {
    t += profile.timeDeltas[i] ?? 0;
    if (t > limitUs) break;
    const dt = (profile.timeDeltas[i + 1] ?? 0) / 1000;
    const n = byId.get(profile.samples[i]);
    if (!n || n.callFrame.functionName === '(idle)' || n.callFrame.functionName === '(program)') continue;
    busy += dt;
    self.set(label(n.callFrame), (self.get(label(n.callFrame)) ?? 0) + dt);
    perScript.set(short(n.callFrame.url), (perScript.get(short(n.callFrame.url)) ?? 0) + dt);
    const seen = new Set();
    for (let id = n.id; id !== undefined; id = parent.get(id)) {
      const cf = byId.get(id).callFrame;
      if (!/(main|editor)\.cjs$/.test(cf.url)) continue;
      const l = label(cf);
      if (seen.has(l)) continue;
      seen.add(l);
      incl.set(l, (incl.get(l) ?? 0) + dt);
    }
  }
  const top = (m, k) => [...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, k).map(([fn, ms]) => ({ fn, ms: Math.round(ms) }));
  return { busyMs: Math.round(busy), selfTop: top(self, 15), inclusiveTop: top(incl, 25), perScript: top(perScript, 10) };
}

// ------------------------------------------------------------------------------------------- core bench

/**
 * The map's two parts, timed with core's own functions in Electron's Node (ELECTRON_RUN_AS_NODE): read, hash,
 * decode; buildMap, which since review finding 31 does what the served copy needs (Strategy 1: the parse5
 * walk, stamps, notes block) and leaves the rest to the first read (Strategy 2: script and JSON literals,
 * object keys, their shadows; mapper.ts completeMap); the served copy and its encoding; the rest of the map;
 * and the client map sent to the deck. With a core that builds the whole map at once, `mapRestMs` is 0.
 */
const CORE_BENCH = `
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { decodeDeck, encodeDeck } from '@blueline/core/text';
import * as mapper from '@blueline/core/mapper';
import { buildServedCopy } from '@blueline/core/served';
const job = JSON.parse(readFileSync(process.argv[process.argv.length - 1], 'utf8'));
const runs = [];
for (let k = 0; k < job.runs + 1; k++) {
  const t0 = performance.now();
  const bytes = new Uint8Array(readFileSync(job.file));
  const t1 = performance.now();
  const version = createHash('sha256').update(bytes).digest('hex');
  const t2 = performance.now();
  const d = decodeDeck(bytes);
  const t3 = performance.now();
  const map = mapper.buildMap(d.src, { version, utf8: d.utf8 });
  const t4 = performance.now();
  const body = encodeDeck(buildServedCopy(d.src, map, { protected: false }));
  const t5 = performance.now();
  if (typeof mapper.completeMap === 'function') mapper.completeMap(map);
  const t6 = performance.now();
  const client = d.utf8 ? mapper.toClientMap(map) : null;
  const t7 = performance.now();
  void body;
  void client;
  // The first run warms the JIT; it is not counted.
  if (k > 0) runs.push({ readMs: t1 - t0, hashMs: t2 - t1, decodeMs: t3 - t2, mapServedPartMs: t4 - t3, servedCopyMs: t5 - t4, mapRestMs: t6 - t5, clientMapMs: t7 - t6 });
}
writeFileSync(job.out, JSON.stringify({ bytes: readFileSync(job.file).length, runs }));
`;

async function coreBench(o, work) {
  const esbuild = await import('esbuild');
  const outfile = join(work, 'core-bench.cjs');
  const coreSubpaths = {
    name: 'core-subpaths',
    setup(build) {
      build.onResolve({ filter: /^@blueline\/core\// }, (a) => ({ path: join(ROOT, 'packages/core/src', a.path.slice('@blueline/core/'.length) + '.ts') }));
    },
  };
  await esbuild.build({ stdin: { contents: CORE_BENCH, resolveDir: ROOT, loader: 'js' }, bundle: true, platform: 'node', format: 'cjs', target: 'node24', outfile, logLevel: 'error', plugins: [coreSubpaths] });
  const job = join(work, 'core-bench-job.json');
  const out = join(work, 'core-bench.json');
  writeFileSync(job, JSON.stringify({ file: o.deck, runs: o.runs, out }));
  const code = await new Promise((res) => {
    const c = spawn(electronBinary(), [outfile, job], { env: { ...appEnv({}), ELECTRON_RUN_AS_NODE: '1' }, stdio: ['ignore', 'ignore', 'inherit'] });
    c.on('exit', res);
    c.on('error', () => res(-1));
  });
  if (code !== 0 || !existsSync(out)) return { error: `core bench exit ${code}` };
  const r = JSON.parse(readFileSync(out, 'utf8'));
  return { ...r, median: medians(r.runs) };
}

/** ms per MB of the deck (the main-process share grows with the file's markup and code, not only its size). */
export function perMb(ms, bytes) {
  return typeof ms === 'number' && bytes > 0 ? ms / (bytes / 1024 / 1024) : null;
}

