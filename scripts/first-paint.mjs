function fmt(x) {
  return typeof x === 'number' ? `${Math.round(x)}` : '–';
}

async function main() {
  const o = parseArgs(process.argv.slice(2));
  if (!existsSync(join(APP_DIR, 'dist/main.cjs'))) usage('packages/app/dist/main.cjs is missing: run `npm run build` first');
  if (!o.deck) {
    o.deck = DEFAULT_DECK;
    if (!existsSync(o.deck)) {
      const { generate } = await import('../fixtures/perf/generate.mjs');
      mkdirSync(join(ROOT, 'fixtures/perf/out'), { recursive: true });
      writeFileSync(o.deck, generate().html);
    }
  }
  const bytes = readFileSync(o.deck).length;
  const work = o.work ?? join(ROOT, 'test-results/parity/first-paint');
  rmSync(work, { recursive: true, force: true });
  mkdirSync(join(work, 'decks'), { recursive: true });
  const out = o.out ?? join(ROOT, 'test-results/parity/first-paint.json');
  mkdirSync(resolve(out, '..'), { recursive: true });
  const disp = await ensureDisplay();
  const result = { kind: 'first-paint', started: new Date().toISOString(), deck: { file: o.deck.startsWith(ROOT) ? o.deck.slice(ROOT.length + 1) : 'deck.html', bytes }, runs: o.runs, gateMs: GATE_MS, env: { platform: process.platform, arch: process.arch, root: IS_ROOT, display: disp.display }, bench: null, core: null, bare: null, trust: {} };
  try {
    // The main-process share, with the app's own functions (exit-gate harness, Electron's Node).
    const { main: harness } = await bundleHarness(join(work, 'harness'));
    const benchOut = join(work, 'bench.json');
    writeFileSync(join(work, 'bench-job.json'), JSON.stringify({ kind: 'bench', file: o.deck, runs: o.runs, out: benchOut, workDir: work }));
    const code = await runElectron(harness, [`--bl-parity-job=${join(work, 'bench-job.json')}`], { env: appEnv({ DISPLAY: disp.display ?? '' }), onLine: (l) => l.startsWith('[parity]') && console.error(l) });
    result.bench = code === 0 && existsSync(benchOut) ? JSON.parse(readFileSync(benchOut, 'utf8')) : { error: `harness exit ${code}` };
    result.core = await coreBench(o, work).catch((e) => ({ error: e.message }));
    result.bare = await bareElectron(work, o.runs, disp.display);
    for (const trust of o.trust) {
      result.trust[trust] = {};
      if (o.warm) result.trust[trust].warm = await warmRuns(o, trust, work, disp.display);
      if (o.cold) result.trust[trust].cold = await coldRuns(o, trust, work, disp.display);
    }
  } finally {
    disp.stop();
  }
  result.finished = new Date().toISOString();

  const mb = bytes / 1024 / 1024;
  console.log(`First paint, ${mb.toFixed(2)} MB deck, ${o.runs} counted runs per case (ms; medians of the runs that painted, "Runs" says how many):`);
  const rows = [['Trust', 'Case', 'Runs', 'Total', 'Open→nav start', 'Protocol 1st byte', 'Body', 'Body end→FCP', 'Nav→FCP']];
  const failures = [];
  let pass = true;
  for (const [trust, r] of Object.entries(result.trust)) {
    if (r.warm) {
      const m = r.warm.median;
      rows.push([trust, 'warm, from open request', runsLabel(r.warm), fmt(m.fromOpen), fmt(m.openToNavStart), fmt(m.protocolFirstByte), fmt(m.protocolBody), fmt(m.responseEndToFcp), fmt(m.navToFcp)]);
      rows.push([trust, 'warm, from 2nd launch', runsLabel(r.warm), fmt(m.fromSpawn), '', '', '', '', '']);
      const pm = r.warm.plain?.median ?? {};
      rows.push([trust, 'plain file:// window (baseline)', runsLabel(r.warm.plain), '', '', fmt(pm.protocolFirstByte), fmt(pm.protocolBody), fmt(pm.responseEndToFcp), fmt(pm.navToFcp)]);
      if (r.warm.failed) failures.push(`${trust} warm: ${r.warm.failed} of ${r.warm.counted} runs failed (${r.warm.errors.join('; ')})`);
      pass &&= caseMeets(r.warm, 'fromOpen');
    }
    if (r.cold) {
      const m = r.cold.median;
      rows.push([trust, 'cold, from app start', runsLabel(r.cold), fmt(m.fromStart), fmt(m.startToDeckNav), fmt(m.protocolFirstByte), fmt(m.protocolBody), fmt(m.responseEndToFcp), fmt(m.navToFcp)]);
      if (r.cold.failed) failures.push(`${trust} cold: ${r.cold.failed} of ${r.cold.counted} runs failed (${r.cold.errors.join('; ')})`);
      pass &&= caseMeets(r.cold, 'fromStart');
    }
  }
  result.pass = pass;
  writeFileSync(out, JSON.stringify(result, null, 1) + '\n');
  const w = rows[0].map((_, i) => Math.max(...rows.map((r) => String(r[i]).length)));
  for (const r of rows) console.log(r.map((c, i) => String(c).padEnd(w[i])).join('  '));
  for (const f of failures) console.log(f);
  const b = result.bench?.median;
  const ms = (x) => `${x.toFixed(1)} (${perMb(x, bytes).toFixed(0)} ms/MB)`;
  if (b) console.log(`Main process (harness, median of ${result.bench.runs.length}): read ${b.readMs.toFixed(1)}, hash ${b.hashMs.toFixed(1)}, decode ${b.decodeMs.toFixed(1)}, buildMap ${ms(b.mapMs)}, served copy ${b.servedMs.toFixed(1)}, encode ${b.encodeMs.toFixed(1)}; loadDocument ${ms(b.loadDocumentMs)}, protocol response ${b.protocolMs.toFixed(1)}; main's share ${ms(b.loadDocumentMs + b.protocolMs)}`);
  else console.log(`Main process (harness): ${result.bench?.error ?? 'not measured'}`);
  const c = result.core?.median;
  if (c) console.log(`Map (core, median of ${result.core.runs.length}): before serving (Strategy 1) ${ms(c.mapServedPartMs)}, served copy and encoding ${c.servedCopyMs.toFixed(1)}; the rest on first read (Strategy 2) ${ms(c.mapRestMs)}, client map ${c.clientMapMs.toFixed(1)}`);
  else console.log(`Map (core): ${result.core?.error ?? 'not measured'}`);
  if (result.bare?.median?.toReady) console.log(`Bare Electron start to ready: ${fmt(result.bare.median.toReady)}`);
  for (const [trust, r] of Object.entries(result.trust)) {
    const p = r.cold?.profile;
    if (p && !p.error) console.log(`Cold start profile (${trust}), main busy ${p.busyMs} ms before first paint; inclusive: ${p.inclusiveTop.slice(0, 8).map((x) => `${x.fn.split(' ')[0]} ${x.ms}`).join(', ')}`);
  }
  console.log(`Gate (< ${GATE_MS} ms, every counted run painted): ${pass ? 'met' : 'NOT met'}. Results: ${out}`);
  process.exit(pass ? 0 : 1);
}

